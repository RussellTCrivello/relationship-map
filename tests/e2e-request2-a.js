'use strict';
// Request 2 Part A browser smoke check: events, locations, routes, filters and time controls.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { chromium } = require('playwright');

async function run() {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'rm-location-editor-'));
  Object.assign(process.env, { DB_ENGINE: 'file', DATA_FILE: path.join(tmp, 'db.json'), ADMIN_USERNAME: 'admin', ADMIN_PASSWORD: 'test-password-123' });
  const { getAdmin } = require('../server/auth.js');
  await getAdmin();
  const { app } = require('../server/app.js');
  const server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, locale: 'ar' });
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
  await page.route(url => !/^http:\/\/127\.0\.0\.1/.test(url.href) && !/^(data|blob):/.test(url.href), r => r.abort());
  try {
    const baseUrl = `http://127.0.0.1:${server.address().port}`;
    const login = await page.request.post(baseUrl + '/api/auth/login', { data: { username: 'admin', password: 'test-password-123' } });
    assert.ok(login.ok(), `login failed: ${login.status()}`);
    await page.goto(baseUrl, { waitUntil: 'domcontentloaded' });
    await page.waitForSelector('#login-screen[hidden]', { state: 'attached' });
    await page.waitForFunction(() => window.RelationshipHost?.state?.nodes?.some(n => n.schema !== 'Event'));
    const id = await page.evaluate(() => { const h = window.RelationshipHost, n = h.state.nodes.find(n => n.schema !== 'Event'); h.selectNode(String(n.id)); return String(n.id); });
    await page.click('[data-tab="events"]'); await page.click('[data-ev-add]');
    await page.fill('#evx-title', 'حدث بموقع');
    await page.fill('#evx-date-exact', '2026-03-14');
    await page.click('#evx-location summary');
    await page.fill('#evx-geo-fields #gx-coords', '31.50000, 34.40000');
    await page.fill('#evx-geo-fields #gx-place', 'غزة');
    await page.fill('#evx-geo-fields #gx-note', 'ملاحظة محفوظة');
    await page.fill('#evx-geo-fields #gx-to-coords', '31.50100, 34.40100');
    await page.fill('#evx-geo-fields #gx-to-place', 'الوجهة');
    await page.locator('#evx-geo-fields #gx-file').setInputFiles(path.join(__dirname, 'fixtures', 'location.png'));
    await page.waitForSelector('#evx-geo-fields [data-cap="0"]');
    await page.fill('#evx-geo-fields [data-cap="0"]', 'صورة الحدث');
    assert.match(await page.locator('#gx-distance').innerText(), /المسافة/);
    await page.click('#evx-geo-fields #gx-pick');
    await page.waitForSelector('#ev-edit:not(.open)', { state: 'attached' });
    await page.keyboard.press('Escape');
    await page.waitForSelector('#ev-edit.open');
    assert.equal(await page.inputValue('#evx-title'), 'حدث بموقع');
    assert.equal(await page.inputValue('#evx-geo-fields #gx-place'), 'غزة');
    await page.click('#evx-geo-fields #gx-pick');
    await page.waitForSelector('#ev-edit:not(.open)', { state: 'attached' });
    const canvasBox = await page.locator('#geo-canvas').boundingBox();
    await page.mouse.click(canvasBox.x + canvasBox.width * .45, canvasBox.y + canvasBox.height * .45);
    await page.waitForSelector('#ev-edit.open');
    assert.equal(await page.inputValue('#evx-title'), 'حدث بموقع');
    assert.equal(await page.inputValue('#evx-geo-fields #gx-place'), 'غزة');
    await page.fill('#evx-geo-fields #gx-coords', '31.50000, 34.40000');
    await page.click('#evx-form button[type="submit"]');
    await page.waitForSelector('#ev-edit:not(.open)', { state: 'attached' });
    const record = await page.evaluate(id => window.RelationshipHost.state.data.nodes.find(n => String(n.id) === id).events.find(e => e.title === 'حدث بموقع'), id);
    assert.equal(record.geo.place, 'غزة'); assert.equal(record.geo.note, 'ملاحظة محفوظة');
    assert.equal(record.geo.photos[0].caption, 'صورة الحدث'); assert.match(record.geo.photos[0].src, /^data:image\//);
    assert.deepEqual(record.geo.to, { lat: 31.501, lng: 34.401, place: 'الوجهة' });
    await page.waitForFunction(() => !window.RelationshipMap._state.initializing && window.RelationshipMap._state.areaStorageReady);
    await page.evaluate(() => { const m = window.RelationshipMap, st = m._state; cancelAnimationFrame(st.fly); st.lat = 31.5; st.lng = 34.4; st.z = 16; st.positioned = true; m._setView('map'); m.sync(true); });
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await page.waitForFunction(() => window.RelationshipMap._state.routeHits?.length > 0);
    await page.waitForSelector('.geo-pin[data-kind="personal-event"]');
    const target = await page.evaluate(() => { const hits = window.RelationshipMap._state.routeHits; const p = hits[0].pts.at(-1), r = document.querySelector('#geo-canvas').getBoundingClientRect(); return { x: r.x + p.x, y: r.y + p.y }; });
    await page.mouse.click(target.x, target.y);
    await page.waitForSelector('#geo-card:not([hidden])');
    assert.match(await page.locator('#geo-card').innerText(), /حدث بموقع/);
    await page.click('#geo-card [data-geo-close]');
    await page.click('.geo-pin[data-kind="personal-event"]');
    await page.waitForSelector('#geo-card:not([hidden])');
    const card = await page.locator('#geo-card').innerText();
    assert.match(card, /حدث بموقع/); assert.match(card, /14 مارس 2026/); assert.match(card, /غزة/); assert.match(card, /ملاحظة محفوظة/);
    assert.equal(await page.evaluate(() => window.RelationshipHost.state.selected), id);
    await page.click('#geo-card [data-geo-edit]');
    await page.waitForSelector('#ev-edit.open');
    assert.equal(await page.inputValue('#evx-geo-fields #gx-place'), 'غزة');
    await page.click('#ev-edit header button[data-edit-close]');
    await page.click('#geo-card [data-geo-graph]');
    assert.equal(await page.evaluate(() => window.RelationshipHost.state.selected), id);
    await page.evaluate(id => {
      const h = window.RelationshipHost, n = h.state.data.nodes.find(n => String(n.id) === id);
      n.events.push({ id: 'second-journey', title: 'محطة أخرى', type: 'travel', date: '2025-04-01', datePrecision: 'exact', geo: { lat: 31.502, lng: 34.402 } });
      h.refreshAfterMutation('إضافة محطة تجريبية', id, { keepView: true });
      const m = window.RelationshipMap; m._state.layers.journey = true; m._setView('map'); m.sync(true);
    }, id);
    await page.waitForFunction(() => document.querySelector('#geo-journey-total')?.textContent.includes('2 محطات'));
    assert.match(await page.locator('#geo-journey-total').innerText(), /مسار الكيان/);
    await page.waitForSelector('#geo-timebar:not([hidden])');
    const bounds = await page.evaluate(() => ({ ...window.RelationshipMap._state.time.range }));
    await page.locator('#geo-time-slider').evaluate((el, v) => { el.value = v; el.dispatchEvent(new Event('input', { bubbles: true })); }, bounds.min);
    await page.waitForFunction(() => window.RelationshipMap._state.time.cursor === window.RelationshipMap._state.time.range.min);
    assert.match(await page.locator('#geo-time-date').innerText(), /2025/);
    await page.selectOption('#geo-time-speed', '4'); await page.click('#geo-time-play');
    await page.waitForFunction(() => window.RelationshipMap._state.time.playing === true);
    await page.keyboard.press('Escape');
    assert.equal(await page.evaluate(() => window.RelationshipMap._state.time.playing), false);
    await page.locator('#geo-time-slider').evaluate((el, v) => { el.value = v; el.dispatchEvent(new Event('input', { bubbles: true })); }, bounds.max);
    await page.selectOption('#geo-time-mode', 'window'); await page.selectOption('#geo-time-months', '1');
    await page.waitForSelector('.geo-pin[data-kind="personal-event"]');
    await page.click('.geo-pin[data-kind="personal-event"]');
    const out = path.join(__dirname, '..', 'docs', 'screenshots', 'request-2'); fs.mkdirSync(out, { recursive: true });
    for (const width of [1440, 700, 390]) {
      await page.setViewportSize({ width, height: 900 });
      await page.waitForTimeout(100);
      const overlaps = await page.evaluate(() => {
        const rect = sel => document.querySelector(sel).getBoundingClientRect();
        const a = rect('#geo-card'), bar = rect('#geo-timebar'), controls = rect('.geo-controls'), search = rect('#geo-map-searchbox');
        const hit = (x, y) => x.left < y.right && x.right > y.left && x.top < y.bottom && x.bottom > y.top;
        return { time: hit(a, bar), controls: hit(a, controls), search: hit(a, search) };
      });
      assert.deepEqual(overlaps, { time: false, controls: false, search: false }, `overlap at ${width}px`);
      await page.screenshot({ path: path.join(out, `part-a-${width}.png`) });
    }
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.click('#geo-filter-btn');
    await page.uncheck('[data-filter-kind="personal-event"]');
    assert.equal(await page.locator('#geo-filter-badge').innerText(), '1');
    await page.waitForFunction(() => document.querySelectorAll('.geo-pin[data-kind="personal-event"]').length === 0);
    await page.waitForTimeout(1000); await page.reload();
    await page.waitForSelector('#login-screen[hidden]', { state: 'attached' });
    await page.waitForFunction(id => window.RelationshipHost?.state?.data?.nodes?.find(n => String(n.id) === id)?.events?.some(e => e.title === 'حدث بموقع'), id);
    const saved = await page.evaluate(id => window.RelationshipHost.state.data.nodes.find(n => String(n.id) === id).events.find(e => e.title === 'حدث بموقع').geo, id);
    assert.equal(saved.place, 'غزة'); assert.equal(saved.to.place, 'الوجهة'); assert.equal(saved.photos[0].caption, 'صورة الحدث');
    assert.equal(await page.evaluate(() => window.RelationshipMap._state.filters.kinds['personal-event']), false);
    await page.click('#geo-filter-btn'); await page.click('[data-filter-reset]');
    assert.equal(await page.evaluate(() => window.RelationshipMap._state.filters.kinds['personal-event']), true);
    await page.fill('#search', 'nothing matches this marker 947112');
    await page.waitForFunction(() => window.RelationshipHost.state.search.includes('947112') && document.querySelectorAll('.geo-pin,.geo-cluster').length === 0);
    await page.fill('#search', '');
    await page.evaluate(id => { window.RelationshipMap._setView('graph'); window.RelationshipHost.selectNode(id); }, id);
    await page.click('[data-tab="events"]');
    const entry = page.locator('.ev-entry').filter({ hasText: 'حدث بموقع' });
    const toggle = entry.locator('[data-ev-toggle]');
    if (await toggle.getAttribute('aria-expanded') !== 'true') await toggle.click();
    await entry.locator('[data-pe-edit]').click();
    await page.click('#evx-clear-geo'); await page.click('#evx-form button[type="submit"]');
    await page.waitForSelector('#ev-edit:not(.open)', { state: 'attached' });
    assert.equal(await page.evaluate(id => window.RelationshipHost.state.data.nodes.find(n => String(n.id) === id).events.find(e => e.title === 'حدث بموقع').geo, id), undefined);
    const undoSave = page.waitForResponse(r => r.url().endsWith('/api/graph') && r.request().method() === 'PUT' && (r.request().postData() || '').includes('صورة الحدث') && r.status() === 200, { timeout: 15000 });
    await page.keyboard.press('Control+z');
    await page.waitForFunction(id => window.RelationshipHost.state.data.nodes.find(n => String(n.id) === id).events.find(e => e.title === 'حدث بموقع').geo?.place === 'غزة', id);
    await undoSave;
    const graph = await (await page.request.get(baseUrl + '/api/graph')).json();
    assert.equal(graph.nodes.find(n => String(n.id) === id).events.find(e => e.title === 'حدث بموقع').geo.photos[0].caption, 'صورة الحدث');
    const sharedId = await page.evaluate(id => {
      const h = window.RelationshipHost;
      const res = window.RelationshipChronology.applyDraft(h.state.data, { title: 'حدث مشترك بالخريطة', type: 'meeting', date: '2026-05-01', datePrecision: 'exact', description: 'تفاصيل مشتركة', sources: [], attachments: [], participants: [{ id }], geo: { lat: 31.51, lng: 34.42, place: 'غزة' } }, h.nextId);
      h.refreshAfterMutation('إضافة حدث مشترك', id, { keepView: true });
      const m = window.RelationshipMap; Object.assign(m._state, { lat: 31.51, lng: 34.42, z: 16 }); m._setView('map'); m.sync(true);
      return String(res.node.id);
    }, id);
    await page.waitForSelector('.geo-pin[data-kind="shared-event"]');
    await page.click('.geo-pin[data-kind="shared-event"]');
    await page.waitForSelector('#geo-card:not([hidden])');
    assert.match(await page.locator('#geo-card').innerText(), /حدث مشترك بالخريطة/);
    assert.equal(await page.evaluate(() => window.RelationshipHost.state.selected), sharedId);
    await page.click('#geo-card [data-geo-graph]');
    assert.equal(await page.evaluate(() => window.RelationshipHost.state.selected), sharedId);
    assert.deepEqual(errors, []);
    console.log('Request 2 Part A browser smoke check passed');
  } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); fs.rmSync(tmp, { recursive: true, force: true }); }
}
run().catch(err => { console.error(err); process.exitCode = 1; });
